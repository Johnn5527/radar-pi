GENERICO_MARGINAL = {"MARGINAL", "MARG"}


def normalizar(tok: str) -> str:
    return re.sub(r"[^A-Z]", "", sem_acento(tok or ""))


def resolver(tok: str):
    """-> ('ponto', (lat,lon)) | ('linha', [...]) | ('marginal', None) | None"""
    t = normalizar(tok)
    if not t:
        return None
    if t in GENERICO_MARGINAL:
        return ("marginal", None)
    if t in LINHAS:
        return ("linha", LINHAS[t])
    t = ALIASES.get(t, t)
    if t in LUGARES:
        return ("ponto", LUGARES[t])
    cands = [k for k in LUGARES if k.startswith(t)] if len(t) >= 4 else []
    if len(cands) == 1:
        return ("ponto", LUGARES[cands[0]])
    return None
